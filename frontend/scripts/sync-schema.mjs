// Regenerates src/lib/report-schema.ts from the canonical schema in docs/schema.
// Run after the Rust engine bumps its report schema version: `npm run sync-schema`.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "..", "docs", "schema");
const files = readdirSync(dir).filter((f) => /^report-\d+\.\d+\.\d+\.schema\.json$/.test(f))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
const latest = files[files.length - 1];
if (!latest) throw new Error(`no report-*.schema.json found in ${dir}`);
const schema = JSON.parse(readFileSync(join(dir, latest), "utf8"));
const out =
  `// GENERATED by scripts/sync-schema.mjs from docs/schema/${latest}. Do not edit by hand.\n` +
  `// A test (schema-sync.test.ts) fails if this file drifts from the canonical schema.\n\n` +
  `export const REPORT_SCHEMA_FILE = ${JSON.stringify(latest)};\n\n` +
  `export const REPORT_SCHEMA: unknown = ${JSON.stringify(schema, null, 2)};\n`;
writeFileSync(join(here, "..", "src", "lib", "report-schema.ts"), out);
console.log(`wrote src/lib/report-schema.ts from ${latest}`);
